/** 一個步驟：標題 + 幾句話（可以帶連結）。 */
function step(title, children) {
  return el('li', {}, [el('h3', { text: title }), ...children]);
}

/** 功能卡：頁面名稱 + 這一頁能做什麼。 */
function card(emoji, title, href, children) {
  return el('div', { class: 'guide-card' }, [
    el('h3', {}, [
      el('span', { 'aria-hidden': 'true', text: emoji }),
      href ? el('a', { href, text: title }) : el('span', { text: title }),
    ]),
    el('p', {}, children),
  ]);
}

function faq(question, answer) {
  const box = el('details', { class: 'faq' });
  box.append(el('summary', { text: question }), el('p', {}, answer));
  return box;
}

